package ua.edu.znu.arrayanalizer;

import java.util.Arrays;

/**
 * Допоміжний клас зі статичними методами (допоміжними функціями) для пошуку індексу елемента масиву
 * за допомогою лінійного та бінарного алгоритмів пошуку
 *
 * @author Student
 * @version 1.0
 */
class ArraySearch {
    /**
     * Виконує лінійний пошук елемента масиву.
     *
     * @param array   масив, у якому потрібно виконати пошук
     * @param element елемент, який потрібно знайти
     * @return індекс елемента, якщо він знайдений, або -1, якщо не знайдений
     */
    public static int linearSearch(int[] array, int element) {
        for (int i = 0; i < array.length; i++) {
            if (array[i] == element) {
                return i; // Повертає індекс знайденого елемента
            }
        }
        return -1; // Повертає -1, якщо елемент не знайдено
    }

    /**
     * Виконує бінарний пошук елемента масиву.
     * <p>
     * Бінарний пошук набагато швидший за лінійний пошук,
     * але він вимагає попереднього сортування масиву.
     * Для пошуку створюється та сортується КОПІЯ вхідного масиву,
     * тому оригінальний масив не змінюється.
     *
     * @param array   масив, копія якого буде відсортована для виконання пошуку
     * @param element елемент, який потрібно знайти
     * @return індекс елемента у відсортованій копії масиву, якщо він знайдений, або -1, якщо не знайдений
     */
    public static int binarySearch(int[] array, int element) {
        // Алгоритм бінарного пошуку вимагає сортування вхідного масиву у порядку зростання.
        int[] sortedArray = bubbleSort(array); // Сортування масиву перед виконанням бінарного пошуку
        // Вивести відсортований масив, щоб користувач міг бачити, що сталося
        System.out.println("Відсортований масив для бінарного пошуку: " + Arrays.toString(sortedArray));
        int left = 0;
        int right = sortedArray.length - 1;
        while (left <= right) {
            int mid = left + (right - left) / 2; // Розрахунок середнього індексу
            if (sortedArray[mid] == element) {
                return mid; // Повертає індекс знайденого елемента
            } else if (sortedArray[mid] < element) {
                left = mid + 1; // Пошук у правій половині
            } else {
                right = mid - 1; // Пошук у лівій половині
            }
        }
        return -1; // Повертає -1, якщо елемент не знайдено
    }

    /**
     * Сортує заданий масив за допомогою алгоритму бульбашкового сортування.
     * Не впливає на оригінальний масив, оскільки для бінарного пошуку використовується
     * відсортована КОПІЯ масиву.
     * <p>
     * Це допоміжний PRIVATE метод – його використовує внутрішньо лише клас ArraySearch.
     * Бульбашкове сортування працює шляхом багаторазового перегляду масиву та обміну суміжними елементами,
     * якщо вони знаходяться в неправильному порядку.
     *
     * @param array масив, який потрібно відсортувати
     * @return відсортовану КОПІЮ вхідного масиву
     */
    private static int[] bubbleSort(int[] array) {
        int[] sortedArray = Arrays.copyOf(array, array.length); // Створюємо копію масиву для сортування
        int n = sortedArray.length;
        for (int i = 0; i < n - 1; i++) {
            for (int j = 0; j < n - i - 1; j++) {
                if (sortedArray[j] > sortedArray[j + 1]) {
                    // Поміняти місцями sortedArray[j] та sortedArray[j + 1], якщо лівий елемент більший
                    int temp = sortedArray[j];
                    sortedArray[j] = sortedArray[j + 1];
                    sortedArray[j + 1] = temp;
                }
            }
        }
        return sortedArray; // Повернути відсортовану КОПІЮ вхідного масиву
    }
}
